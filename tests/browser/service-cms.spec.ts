import { test, expect } from "@playwright/test";
import { loadEnvConfig } from "@next/env";
import { createServerClient } from "@supabase/ssr";
import { readFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import type { Block, Snapshot } from "../../lib/admin/types";
loadEnvConfig(process.cwd());
const local = process.env.NEXT_PUBLIC_SUPABASE_URL === "http://127.0.0.1:57321";

test("service CMS: edit copy/icons/images, save, preview, publish, then remove content permanently", async ({ page, context }) => {
  test.skip(!local, "Requiere el entorno local.");
  page.setDefaultTimeout(10000);
  const fixtures = JSON.parse(readFileSync(".local/albar-fixtures.json", "utf8"));
  const accounts = JSON.parse(readFileSync(".local/admin-accounts.json", "utf8"));
  const jar = new Map<string, string>();
  const db = createServerClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY!, { cookies: { getAll: () => [...jar].map(([name, value]) => ({ name, value })), setAll: cookies => cookies.forEach(c => jar.set(c.name, c.value)) } });
  const login = await db.auth.signInWithPassword(accounts.admin); expect(login.error).toBeNull();
  await context.addCookies([...jar].map(([name, value]) => ({ name, value, url: "http://localhost:3000" })));
  const entry = await db.from("content_entries").insert({ site_id: fixtures.siteId, internal_name: "Prueba de editor dinámico", kind: "landing", locale: "es-CL" }).select("id").single(); expect(entry.error).toBeNull();
  const entryId = entry.data!.id;
  const block = (type: string, data: Block["data"], variant = "default"): Block => ({ key: randomUUID(), type, data, variant, schema_version: 1, assets: [] });
  const blocks = [block("hero", { heading: "Portada editable", body: "Texto inicial", note: "Nota inicial", visual: "image", actions: [] }), block("card_grid", { items: [{ heading: "Beneficio inicial", body: "Detalle inicial", icon: "none" }], tone: "sage", columns: "4" }, "benefits"), block("cta", { heading: "Cierre editable", actions: [{ label: "Contacto inicial", href: "/contacto", style: "primary", icon: "none" }] })];
  blocks[0].assets = [{ asset_id: fixtures.assets["claudia-perfil"], slot: "image", alt_text: "Retrato del estudio", focal_point: { x: .5, y: .5 } }];
  const content: Snapshot = { title: "Servicio de prueba CMS", path: `/servicio-cms-${randomUUID()}`, excerpt: "", cover_asset_id: null, template_key: "service-landing", template_version: 2, blocks, seo: {}, authors: [], terms: [], relations: [] };
  const initial = await db.rpc("save_content_revision", { p_entry_id: entryId, p_expected_revision_id: null, p_content: content }); expect(initial.error).toBeNull();
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  async function saveAndPublish() {
    await page.getByRole("button", { name: "Guardar revisión", exact: true }).click();
    await expect(page.getByRole("status").filter({ hasText: "Nueva revisión guardada." })).toBeVisible();
    await page.getByRole("button", { name: "Enviar a revisión", exact: true }).click();
    await expect(page.getByRole("button", { name: "Enviar a revisión", exact: true })).toBeDisabled();
    await page.getByRole("button", { name: "Aprobar revisión", exact: true }).click();
    await expect(page.getByRole("button", { name: "Aprobar revisión", exact: true })).toBeDisabled();
    await page.getByRole("button", { name: "Publicar revisión", exact: true }).click();
    await page.getByRole("dialog").getByRole("button", { name: "Confirmar", exact: true }).click();
    await expect(page.getByRole("dialog")).toBeHidden();
  }
  try {
    await page.goto(`/admin/content/${entryId}`);
    const hero = page.locator(".editor-block").nth(0);
    await hero.getByLabel("Nota de apoyo", { exact: true }).fill("Nota cambiada desde el panel");
    await hero.getByLabel("Icono de la nota").selectOption("message-circle");
    await hero.getByLabel("Apoyo visual", { exact: true }).selectOption("brand");
    const benefits = page.locator(".editor-block").nth(1);
    await benefits.getByLabel("Título", { exact: true }).fill("Beneficio cambiado desde el panel");
    await benefits.getByLabel("Icono", { exact: true }).selectOption("coins");
    await benefits.getByLabel("Superficie", { exact: true }).selectOption("sand");
    await benefits.getByLabel("Columnas en escritorio").selectOption("2");
    await benefits.getByRole("button", { name: "Imagen del elemento", exact: true }).click();
    const library = page.getByRole("dialog");
    await library.getByLabel("Buscar recurso").fill("claudia-perfil.webp");
    await library.getByRole("button", { name: "Seleccionar claudia-perfil.webp (público)", exact: true }).click();
    await expect(library).toBeHidden();
    await page.locator(".editor-block").nth(2).getByLabel("Texto del botón", { exact: true }).fill("Consultar con el equipo");
    await page.locator(".editor-block").nth(2).getByLabel("Estilo del botón", { exact: true }).selectOption("text");
    await saveAndPublish();
    const previewPromise = context.waitForEvent("page");
    await page.getByRole("link", { name: "Previsualizar guardado" }).click();
    const preview = await previewPromise;
    await expect(preview.locator(".public-site h1")).toHaveText("Portada editable");
    await expect(preview.locator(".public-site .public-action-note")).toHaveText("Nota cambiada desde el panel");
    await expect(preview.locator(".service-benefit .lucide-coins")).toHaveCount(1);
    await expect(preview.locator(".service-item-image img")).toBeVisible();
    await expect(preview.locator(".block-hero img")).toHaveCount(0);
    await expect(preview.locator(".block-hero .service-brand-visual")).toBeVisible();
    await expect(preview.getByRole("link", { name: "Consultar con el equipo", exact: true })).toHaveCSS("background-color", "rgba(0, 0, 0, 0)");
    await preview.close();
    const route = fixtures.basePath + content.path;
    await page.goto(route);
    await expect(page.locator(".service-benefits")).toHaveAttribute("data-tone", "sand");
    await expect(page.getByRole("link", { name: "Consultar con el equipo", exact: true })).toBeVisible();
    await expect(page.locator(".service-item-image img")).toBeVisible();
    await expect(page.locator(".block-hero img")).toHaveCount(0);
    await page.goto(`/admin/content/${entryId}`);
    await page.locator(".editor-block").nth(0).getByLabel("Nota de apoyo", { exact: true }).fill("");
    await page.locator(".editor-block").nth(0).getByLabel("Apoyo visual", { exact: true }).selectOption("none");
    await page.locator(".editor-block").nth(1).getByRole("button", { name: "Quitar bloque", exact: true }).click();
    await page.getByRole("dialog").getByRole("button", { name: "Confirmar", exact: true }).click();
    await saveAndPublish();
    await page.goto(route);
    await expect(page.locator(".service-benefits")).toHaveCount(0);
    await expect(page.locator(".block-hero .public-action-note")).toHaveCount(0);
    await expect(page.locator(".block-hero .service-brand-visual")).toHaveCount(0);
    await expect(page.locator(".block-hero img")).toHaveCount(0);
    expect(errors).toEqual([]);
  } finally {
    await db.rpc("unpublish_content", { p_entry_id: entryId, p_archive: true });
    await db.auth.signOut();
  }
});
